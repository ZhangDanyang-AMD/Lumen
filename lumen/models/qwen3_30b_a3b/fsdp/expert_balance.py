def expert_slot(layer: int) -> list[int]:
    """Return original_expert -> contiguous slot for one decoder layer."""
    if not 0 <= layer < 48:
        raise IndexError(f"expert placement has 48 layers, got {layer}")
    start = layer * 128
    return list(_SLOT[start : start + 128])
